// Copies the self-hosted font subsets from Fontsource into public/fonts and writes
// src/styles/fonts.css. Run after installing or upgrading the font packages:
//   node scripts/copy-fonts.mjs
// Only the latin and latin-ext subsets ship; the browser downloads latin-ext only
// when a page uses one of its characters (for example ₹).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const out = join(root, 'public', 'fonts');
mkdirSync(out, { recursive: true });

const ranges = {
  latin:
    'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  'latin-ext':
    'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF'
};

const faces = [
  { pkg: 'manrope', family: 'Manrope', file: 'manrope', styles: [[400, 'normal'], [500, 'normal'], [600, 'normal'], [700, 'normal'], [800, 'normal']] },
  {
    pkg: 'cormorant-garamond', family: 'Cormorant Garamond', file: 'cormorant-garamond',
    styles: [[400, 'normal'], [500, 'normal'], [600, 'normal'], [700, 'normal'], [400, 'italic'], [500, 'italic']]
  }
];

let css = '/* Generated by scripts/copy-fonts.mjs. Do not edit by hand. */\n';
for (const f of faces) {
  for (const [weight, style] of f.styles) {
    for (const subset of ['latin-ext', 'latin']) {
      const name = `${f.file}-${subset}-${weight}-${style}.woff2`;
      copyFileSync(join(root, 'node_modules', '@fontsource', f.pkg, 'files', name), join(out, name));
      css += `@font-face{font-family:'${f.family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(/fonts/${name}) format('woff2');unicode-range:${ranges[subset]}}\n`;
    }
  }
}

// Metric-matched local fallbacks keep layout shift low while the web fonts load.
css += "@font-face{font-family:'Manrope Fallback';src:local('Segoe UI'),local('Arial');size-adjust:103%;ascent-override:104%;descent-override:29%;line-gap-override:0%}\n";
css += "@font-face{font-family:'Cormorant Fallback';src:local('Garamond'),local('Times New Roman');size-adjust:88%;ascent-override:104%;descent-override:32%;line-gap-override:0%}\n";

writeFileSync(join(root, 'src', 'styles', 'fonts.css'), css);
console.log('Fonts copied to public/fonts and src/styles/fonts.css written.');
